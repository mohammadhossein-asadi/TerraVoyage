export const getAccommodationsByDestination = (slug: string): Accommodation[] =>
  accommodations.filter((a) => a.destinationSlug === slug);

export const getFeaturedAccommodations = (): Accommodation[] =>
  accommodations.filter((a) => a.featured);

export const searchAccommodations = (query: string): Accommodation[] => {
  const q = query.toLowerCase();
  return accommodations.filter(
    (a) =>
      a.name.toLowerCase().includes(q) ||
      a.type.toLowerCase().includes(q) ||
      a.destinationSlug.toLowerCase().includes(q) ||
      a.amenities.some((am) => am.toLowerCase().includes(q))
  );
};
